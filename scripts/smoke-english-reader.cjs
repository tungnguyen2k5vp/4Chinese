/* Isolated WEB evidence; never uses a user browser profile or real learner data. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.argv[2] || 'playwright');
const output = path.resolve(__dirname, '../artifacts/v7-2026-10-11/learner-ui-reader');
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const result = { platform: 'WEB_HEADLESS_NOT_ANDROID', passed: [], errors };
  const base = 'http://localhost:8100';
  try {
    await page.goto(base + '/english');
    await page.getByText('Chưa có bộ từ. Tạo một bộ để bắt đầu.', { exact: true }).waitFor({ timeout: 120000 });
    await page.getByLabel('Tên bộ từ tiếng Anh', { exact: true }).fill('Reader QA');
    await page.getByRole('button', { name: 'Tạo bộ từ', exact: true }).click();
    await page.getByRole('button', { name: 'Đang chọn: Reader QA', exact: true }).waitFor();
    await page.getByLabel('Từ hoặc cụm tiếng Anh', { exact: true }).fill('book');
    await page.getByLabel('Nghĩa tiếng Việt do bạn chọn', { exact: true }).fill('sách cá nhân QA');
    await page.getByRole('button', { name: 'Lưu thẻ vào bộ đang chọn', exact: true }).click();
    await page.getByText('1 thẻ · 0 đã học · 0 đến hạn', { exact: true }).waitFor();
    await page.goto(base + '/english/activity');
    await page.getByRole('button', { name: 'Đọc văn bản tiếng Anh cá nhân', exact: true }).click();
    await page.getByLabel('Văn bản tiếng Anh để đọc', { exact: true }).waitFor({ timeout: 120000 });
    await page.getByLabel('Tiêu đề văn bản tiếng Anh', { exact: true }).fill('Personal Reader QA');
    const text = ("Book. Don't stop; co-workers read! 🙂\n".repeat(200));
    await page.getByLabel('Văn bản tiếng Anh để đọc', { exact: true }).fill(text);
    await page.getByRole('button', { name: 'Lưu và đọc văn bản', exact: true }).click();
    await page.getByText('Đã lưu văn bản và vị trí đọc trên thiết bị.', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Tra từ cá nhân: Book', exact: true }).first().click();
    await page.getByText('sách cá nhân QA', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, '01-reader-personal-lookup.png') });
    result.passed.push('real UI entry from activity, source punctuation and contractions, exact personal lookup');
    await page.getByRole('button', { name: 'Đóng tra từ', exact: true }).click();
    await context.setOffline(true);
    await page.getByRole('button', { name: 'Tra từ cá nhân: co-workers', exact: true }).first().click();
    await page.getByText('Chưa tìm thấy dạng từ này trong bộ từ cá nhân. Không tự đổi sang lemma.', { exact: true }).waitFor();
    await page.getByLabel('Nghĩa cá nhân cho từ đang đọc', { exact: true }).fill('đồng nghiệp QA');
    await page.getByRole('button', { name: 'Đóng tra từ', exact: true }).click();
    await page.getByText('Hãy lưu thẻ hoặc xóa nghĩa đang nhập trước khi đóng phần tra từ.', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Thêm từ đang đọc vào bộ từ', exact: true }).click();
    await page.getByText('Đã thêm thẻ cá nhân. Chưa bắt đầu SRS, không cộng XP khi đọc.', { exact: true }).waitFor();
    await page.getByText('đồng nghiệp QA', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, '02-reader-offline-new-card.png') });
    await page.getByRole('button', { name: 'Đóng tra từ', exact: true }).click();
    await page.getByRole('button', { name: 'Đọc phần tiếp theo', exact: true }).click();
    await page.getByText(/^Vị trí [1-9]\d* \/ /).waitFor();
    const position = await page.getByText(/^Vị trí \d+ \/ /).innerText();
    assert.ok(!position.startsWith('Vị trí 0 /'));
    await page.screenshot({ path: path.join(output, '02-reader-offline-next.png') });
    result.passed.push('loaded offline reads/adds explicit USER meaning, protects unsubmitted meaning on close, saves next whole-word reading offset');
    await context.setOffline(false);
    await page.reload();
    await page.getByText(position, { exact: true }).waitFor({ timeout: 120000 });
    await page.setViewportSize({ width: 320, height: 740 });
    await page.emulateMedia({ colorScheme: 'dark' });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(output, '03-reader-restored-compact-dark.png') });
    await page.getByRole('button', { name: 'Tra từ cá nhân: co-workers', exact: true }).first().click();
    await page.getByText('đồng nghiệp QA', { exact: true }).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(output, '04-reader-lookup-compact-dark.png') });
    await page.getByRole('button', { name: 'Đóng tra từ', exact: true }).click();
    await page.goto(base + '/english');
    await page.getByText('2 thẻ · 0 đã học · 0 đến hạn', { exact: true }).waitFor({ timeout: 120000 });
    await page.getByText('0 lượt ôn · 0 đúng · 0 XP tiếng Anh', { exact: true }).waitFor();
    result.passed.push('cold page reload restores offset; compact dark no document overflow; cards NEW and reviews/XP remain zero');
    assert.deepEqual(errors, []); result.success = true;
  } catch (e) {
    result.success = false; result.failure = e.stack || e.message; process.exitCode = 1;
    await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => {});
  } finally {
    fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify(result, null, 2));
    console.log(JSON.stringify(result)); await browser.close();
  }
})();
