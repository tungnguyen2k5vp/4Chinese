/* Isolated localhost QA. No user browser/profile, cloud calls or native mic claims. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require(process.argv[2]||'playwright');
const origin=process.argv[3]||'http://localhost:8085';
if(!/^http:\/\/(localhost|127\.0\.0\.1):\d+$/.test(origin))throw new Error('LOCALHOST_ONLY');
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const context=await browser.newContext({viewport:{width:412,height:915}});
  const page=await context.newPage();const errors=[];const results=[];let passed=false;let failure=null;
  page.on('pageerror',error=>errors.push(error.message));
  page.on('dialog',dialog=>dialog.accept());
  const text=value=>page.getByText(value,{exact:true});
  try{
    await page.goto(`${origin}/exam`);
    await page.getByRole('radio',{name:'10 phút',exact:true}).click();
    await page.getByRole('switch',{name:'Không quay lại câu trước'}).click();
    await text('Bắt đầu mức 1').click();
    await page.waitForURL(/\/exam\/session/);
    await page.getByText('Câu 1/4',{exact:false}).waitFor();
    await page.getByRole('radio').first().click();
    await text('Đáp án hiện tại đã lưu trên máy.').waitFor();
    await text('Câu tiếp').click();
    await page.getByRole('button',{name:'Chuyển câu',exact:true}).click();
    await page.getByText('Câu 2/4',{exact:false}).waitFor();
    const previous=page.getByRole('button',{name:'Câu trước',exact:true});
    assert.ok(await previous.count()===0||await previous.isDisabled(),'No-back policy exposed previous navigation');
    await page.reload();await page.getByText('Câu 2/4',{exact:false}).waitFor();
    results.push('10-minute selection, no-back high-water position and reload resume');
    await page.goto(`${origin}/reader`);
    const novel='我喜欢学习中文。'.repeat(12500);
    const chooser=page.waitForEvent('filechooser');
    await page.getByRole('button',{name:'Nhập tệp TXT / EPUB',exact:true}).click();
    await(await chooser).setFiles({name:'v5-100k-fixture.txt',mimeType:'text/plain',buffer:Buffer.from(novel,'utf8')});
    await page.getByText('Phần 1/50 · 100.000 ký tự',{exact:true}).waitFor();
    assert.equal(await page.getByRole('textbox',{name:'Văn bản bài đọc'}).count(),0);
    await page.getByRole('button',{name:'Phần sau',exact:true}).click();
    await page.getByText('Phần 2/50 · 100.000 ký tự',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Lưu bài đọc',exact:true}).click();
    await text('Bài đọc đã lưu').waitFor();
    await page.reload();
    await page.getByRole('button',{name:novel.slice(0,30),exact:false}).click();
    await page.getByText('Phần 2/50 · 100.000 ký tự',{exact:true}).waitFor();
    results.push('100k UTF-8 TXT import, 50 lazy chunks, durable part-2 resume after reload');
    await page.getByRole('button',{name:/^我,/}).first().click();
    await page.getByRole('button',{name:'Mở chi tiết từ',exact:true}).click();
    await page.waitForURL(/\/word\//);await page.goBack();
    await page.getByText('Phần 2/50 · 100.000 ký tự',{exact:true}).waitFor();
    results.push('Reader word-detail/back retains semantic chunk');
    await page.goto(`${origin}/listening`);
    await page.getByRole('button',{name:'Chọn câu nghe 1',exact:true}).click();
    const reveal=page.getByRole('button',{name:'Mở bản chép lời và nghĩa',exact:true});await reveal.waitFor();
    await reveal.click();await page.getByRole('button',{name:'Ẩn bản chép lời',exact:true}).waitFor();
    await page.getByRole('tab',{name:'HSK 7-9',exact:true}).click();
    await page.getByText('Chưa có câu đã review ở cấp này.',{exact:false}).waitFor();
    results.push('Listening inline controls, explicit reveal and honest empty advanced level');
    await page.goto(`${origin}/exam/skills`);
    await text('Mở bài / tiếp tục bản nháp').first().waitFor();
    const writingCount=await text('Mở bài / tiếp tục bản nháp').count();assert.ok(writingCount>=7);
    await page.getByRole('tab',{name:'Luyện dịch'}).click();
    const translationCount=await text('Mở bài / tiếp tục bản nháp').count();assert.ok(translationCount>=7);
    results.push(`Written center renders ${writingCount} writing / ${translationCount} translation tasks`);
    await page.goto(`${origin}/mistakes`);await text('Sổ lỗi').first().waitFor();
    await page.getByText('Không có lỗi chưa khắc phục',{exact:false}).waitFor();
    results.push('Error intelligence empty state distinct from loading/failure');
    let providerCalls=0;
    await page.route('**/functions/v1/gemini-conversation',async route=>{providerCalls++;await route.abort();});
    await page.goto(`${origin}/speaking/ai`);
    await page.getByRole('button',{name:'Dùng câu mẫu để luyện',exact:true}).click();
    await page.getByRole('button',{name:'Dùng AI tùy chọn',exact:true}).waitFor();
    assert.ok(await page.getByRole('button',{name:'Dùng AI tùy chọn',exact:true}).isDisabled());
    await page.getByRole('button',{name:'Luyện với kịch bản offline',exact:true}).click();
    await page.getByText('Đã dùng 1/8 lượt',{exact:false}).waitFor();
    assert.equal(providerCalls,0);
    results.push('Offline roleplay works without provider calls; AI mode blocked before consent');
    await page.getByRole('button',{name:'Tôi đồng ý gửi chữ tối thiểu khi dùng AI',exact:true}).click();
    await page.getByRole('button',{name:'Dùng AI tùy chọn',exact:true}).click();
    await page.getByRole('button',{name:'Gửi chữ đã kiểm tra lên AI',exact:true}).waitFor();
    await page.getByRole('button',{name:'Rút đồng ý · quay về offline',exact:true}).click();
    await page.getByRole('button',{name:'Luyện với kịch bản offline',exact:true}).waitFor();
    assert.equal(providerCalls,0);
    results.push('Granting/revoking AI consent changes mode without sending private offline history');
    await page.setViewportSize({width:360,height:800});await page.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'});
    await page.goto(`${origin}/listening`);
    await page.getByRole('button',{name:'Chọn câu nghe 1',exact:true}).click();
    await page.getByRole('button',{name:'Mở bản chép lời và nghĩa',exact:true}).waitFor();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Compact viewport overflow');
    await page.screenshot({path:'docs/v5-listening-dark.png',fullPage:true});
    results.push('360px dark/reduced-motion listening renders without horizontal overflow');
    assert.deepEqual(errors,[]);passed=true;
  }catch(error){failure=error.message;process.exitCode=1;}
  finally{
    await page.screenshot({path:'docs/v5-web-smoke.png',fullPage:true});
    fs.writeFileSync('docs/V5_WEB_SMOKE.json',JSON.stringify({at:new Date().toISOString(),origin,passed,results,errors,failure,nativeDeviceTested:false,geminiTested:false},null,2));
    console.log(JSON.stringify({passed,results,errors,failure}));await browser.close();
  }
})();
